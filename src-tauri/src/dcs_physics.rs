//! Passive, loopback-only DCS ownship export. The runtime owns one Source;
//! consumers clone its capture rather than binding a second UDP socket.
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{collections::BTreeMap, sync::OnceLock, time::Instant};

mod parser;
mod retained;
mod session;
mod source;
pub(crate) use session::Session;
pub(crate) use source::{Reader, Source, SourceView};

pub(crate) const PORT: u16 = 7781;
pub(crate) const MAX_PACKET: usize = 16 * 1024;
pub(crate) const FRESHNESS_MS: u64 = 1000;
pub(crate) const CHANNELS: &str = include_str!("dcs_physics_channels.json");
pub(crate) const EXPORT: &str = include_str!("../../examples/dcs-bios/DCSPhysics.lua");
pub(crate) fn catalogue() -> Vec<Value> {
    serde_json::from_str::<Value>(CHANNELS).expect("bundled DCS ownship catalogue")["channels"]
        .as_array()
        .unwrap()
        .clone()
        .into_iter()
        .map(|mut channel| {
            match channel["type"].as_str() {
                Some("number") => {
                    channel["minimum"] = json!(-1e30);
                    channel["maximum"] = json!(1e30);
                }
                Some("integer") => {
                    channel["minimum"] = json!(-9_007_199_254_740_991i64);
                    channel["maximum"] = json!(9_007_199_254_740_991i64);
                }
                Some("string") => {
                    channel["maxBytes"] = json!(256);
                }
                _ => {}
            }
            channel
        })
        .collect()
}
/// Deterministic managed source; setup owns the exact generated bytes.
pub(crate) fn export_source() -> String {
    let fields = serde_json::to_string(&catalogue()).expect("bundled DCS ownship fields");
    format!("local JSON = require('Scripts.DCS-BIOS.lib.ext.JSON')\nlocal fields = JSON:decode([==[{fields}]==])\n{EXPORT}")
}
pub(crate) fn revision() -> String {
    static REVISION: OnceLock<String> = OnceLock::new();
    REVISION
        .get_or_init(|| {
            let mut digest = Sha256::new();
            digest.update(b"osg-dcs-ownship-v1\0");
            digest.update(export_source().as_bytes());
            digest.update(CHANNELS.as_bytes());
            format!("sha256:{:x}", digest.finalize())
        })
        .clone()
}
