    #[test]
    fn loopback_source_receives_complete_typed_packets_without_a_second_owner() {
        let socket = UdpSocket::bind((Ipv4Addr::LOCALHOST, 0)).unwrap();
        socket.set_nonblocking(true).unwrap();
        let address = socket.local_addr().unwrap();
        let mut source = Source {
            socket,
            session: Session::new(),
            clock: Instant::now(),
            draining: false,
        };
        let sender = UdpSocket::bind((Ipv4Addr::LOCALHOST, 0)).unwrap();
        sender
            .send_to(packet(u32::MAX, 1.0).to_string().as_bytes(), address)
            .unwrap();
        let deadline = Instant::now() + std::time::Duration::from_secs(1);
        while source.poll().unwrap().sequence != Some(u32::MAX) {
            assert!(Instant::now() < deadline);
            std::thread::sleep(std::time::Duration::from_millis(1));
        }
        sender
            .send_to(packet(0, 1.05).to_string().as_bytes(), address)
            .unwrap();
        let capture = loop {
            let value = source.poll().unwrap();
            if value.fresh {
                break value;
            }
            assert!(Instant::now() < deadline);
            std::thread::sleep(std::time::Duration::from_millis(1));
        };
        assert!(capture.fresh);
        assert_eq!(capture.sequence, Some(0));
        assert_eq!(capture.aircraft.as_deref(), Some("FA-18C_hornet"));
        assert_eq!(capture.plane_id, Some(5));
        assert_eq!(capture.model_time, Some(1.05));
        assert_eq!(capture.malformed_frames, 0);
        assert!(capture.error.is_none());
        let mut stopped = packet(1, 1.1);
        stopped["stopped"] = json!(true);
        sender
            .send_to(stopped.to_string().as_bytes(), address)
            .unwrap();
        let stopped = loop {
            let value = source.poll().unwrap();
            if value.status == "stopped" {
                break value;
            }
            assert!(Instant::now() < deadline);
            std::thread::sleep(std::time::Duration::from_millis(1));
        };
        assert_eq!(stopped.status, "stopped");
        assert!(stopped.values.is_empty());
    }
    #[test]
    fn receive_overflow_discards_backlog_without_publishing_old_samples() {
        let socket = UdpSocket::bind((Ipv4Addr::LOCALHOST, 0)).unwrap();
        socket.set_nonblocking(true).unwrap();
        socket2::SockRef::from(&socket)
            .set_recv_buffer_size(1024 * 1024)
            .unwrap();
        let address = socket.local_addr().unwrap();
        let mut source = Source {
            socket,
            session: Session::new(),
            clock: Instant::now(),
            draining: false,
        };
        let sender = UdpSocket::bind((Ipv4Addr::LOCALHOST, 0)).unwrap();
        for index in 0..200 {
            sender
                .send_to(
                    packet(index, index as f64 / 20.0).to_string().as_bytes(),
                    address,
                )
                .unwrap();
        }
        std::thread::sleep(std::time::Duration::from_millis(20));
        let overflow = source.poll().unwrap();
        assert!(!overflow.fresh);
        assert!(overflow.values.is_empty());
        assert!(overflow
            .error
            .as_deref()
            .unwrap()
            .contains("budget exceeded"));
        let drained = source.poll().unwrap();
        assert!(!drained.fresh);
        assert!(drained.values.is_empty());
    }
