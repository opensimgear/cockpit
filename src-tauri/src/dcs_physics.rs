//! Passive, loopback-only DCS ownship export. The runtime owns one Source;
//! consumers clone its capture rather than binding a second UDP socket.
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{
    collections::{BTreeMap, VecDeque},
    net::{Ipv4Addr, SocketAddrV4, UdpSocket},
    sync::OnceLock,
    time::Instant,
};

pub(crate) const PORT: u16 = 7781;
pub(crate) const MAX_PACKET: usize = 16 * 1024;
pub(crate) const FRESHNESS_MS: u64 = 1000;
pub(crate) const CHANNELS: &str = include_str!("dcs_physics_channels.json");
pub(crate) const EXPORT: &str = include_str!("../../examples/dcs-bios/DCSPhysics.lua");
pub(crate) fn catalogue() -> Vec<Value> {
    serde_json::from_str::<Value>(CHANNELS).expect("bundled DCS ownship catalogue")["channels"]
        .as_array()
        .unwrap()
        .clone()
        .into_iter()
        .map(|mut channel| {
            match channel["type"].as_str() {
                Some("number") => {
                    channel["minimum"] = json!(-1e30);
                    channel["maximum"] = json!(1e30);
                }
                Some("integer") => {
                    channel["minimum"] = json!(-9_007_199_254_740_991i64);
                    channel["maximum"] = json!(9_007_199_254_740_991i64);
                }
                Some("string") => {
                    channel["maxBytes"] = json!(256);
                }
                _ => {}
            }
            channel
        })
        .collect()
}
/// Deterministic managed source; setup owns the exact generated bytes.
pub(crate) fn export_source() -> String {
    let fields = serde_json::to_string(&catalogue()).expect("bundled DCS ownship fields");
    format!("local JSON = require('Scripts.DCS-BIOS.lib.ext.JSON')\nlocal fields = JSON:decode([==[{fields}]==])\n{EXPORT}")
}
pub(crate) fn revision() -> String {
    static REVISION: OnceLock<String> = OnceLock::new();
    REVISION
        .get_or_init(|| {
            let mut digest = Sha256::new();
            digest.update(b"osg-dcs-ownship-v1\0");
            digest.update(export_source().as_bytes());
            digest.update(CHANNELS.as_bytes());
            format!("sha256:{:x}", digest.finalize())
        })
        .clone()
}
#[derive(Clone, Debug)]
pub(crate) struct Snapshot {
    pub epoch: u64,
    pub session: Option<String>,
    pub aircraft: Option<String>,
    pub plane_id: Option<u64>,
    pub model_time: Option<f64>,
    pub sequence: Option<u32>,
    pub fresh: bool,
    pub status: String,
    pub age_ms: Option<u64>,
    pub values: BTreeMap<String, Value>,
    pub malformed_frames: u64,
    pub error: Option<String>,
}
struct Packet {
    session: String,
    sequence: u32,
    model_time: f64,
    aircraft: Option<String>,
    plane: Option<u64>,
    allowed: bool,
    paused: bool,
    stopped: bool,
    values: BTreeMap<String, Value>,
}
fn bounded_text(value: &Value, limit: usize) -> Option<&str> {
    value
        .as_str()
        .filter(|s| !s.is_empty() && s.len() <= limit && !s.chars().any(char::is_control))
}
fn parse(bytes: &[u8], fields: &BTreeMap<String, String>) -> Result<Packet, String> {
    let invalid = || "Invalid bounded DCS ownship export packet.".to_owned();
    if bytes.is_empty() || bytes.len() > MAX_PACKET {
        return Err(invalid());
    }
    let value: Value = serde_json::from_slice(bytes).map_err(|_| invalid())?;
    if value["schemaVersion"] != 1 || value["source"] != "osg-dcs-ownship" {
        return Err(invalid());
    }
    let session = bounded_text(&value["session"], 96)
        .ok_or_else(invalid)?
        .to_owned();
    let sequence = value["sequence"]
        .as_u64()
        .and_then(|v| u32::try_from(v).ok())
        .ok_or_else(invalid)?;
    let model_time = value["modelTime"]
        .as_f64()
        .filter(|v| v.is_finite() && *v >= 0.0)
        .ok_or_else(invalid)?;
    let aircraft = if value["aircraft"].is_null() {
        None
    } else {
        Some(
            bounded_text(&value["aircraft"], 256)
                .ok_or_else(invalid)?
                .to_owned(),
        )
    };
    let plane = if value["planeId"].is_null() {
        None
    } else {
        Some(
            value["planeId"]
                .as_u64()
                .filter(|v| *v > 0 && *v <= 9_007_199_254_740_991)
                .ok_or_else(invalid)?,
        )
    };
    let allowed = value["allowed"].as_bool().ok_or_else(invalid)?;
    let paused = value["paused"].as_bool().ok_or_else(invalid)?
        | value["activePause"].as_bool().ok_or_else(invalid)?;
    let stopped = value["stopped"].as_bool().ok_or_else(invalid)?;
    let entries = value["values"]
        .as_object()
        .filter(|v| v.len() <= 128)
        .ok_or_else(invalid)?;
    let mut values = BTreeMap::new();
    for (id, sample) in entries {
        let Some(kind) = fields.get(id) else {
            continue;
        };
        let valid = match kind.as_str() {
            "number" => sample
                .as_f64()
                .is_some_and(|v| v.is_finite() && v.abs() <= 1e30),
            "integer" => sample.as_f64().is_some_and(|v| {
                v.is_finite() && v.fract() == 0.0 && v.abs() <= 9_007_199_254_740_991.0
            }),
            "boolean" => sample.is_boolean(),
            "string" => sample
                .as_str()
                .is_some_and(|v| v.len() <= 256 && !v.chars().any(char::is_control)),
            _ => false,
        };
        if !valid {
            continue;
        }
        values.insert(id.clone(), sample.clone());
    }
    Ok(Packet {
        session,
        sequence,
        model_time,
        aircraft,
        plane,
        allowed,
        paused,
        stopped,
        values,
    })
}
pub(crate) struct Session {
    fields: BTreeMap<String, String>,
    epoch: u64,
    session: Option<String>,
    retired: VecDeque<String>,
    aircraft: Option<String>,
    plane: Option<u64>,
    model_time: Option<f64>,
    sequence: Option<u32>,
    received: Option<u64>,
    status: String,
    values: BTreeMap<String, Value>,
    malformed_frames: u64,
    error: Option<String>,
}
impl Session {
    fn invalidate(&mut self, message: &str) {
        self.epoch = self.epoch.saturating_add(1);
        self.values.clear();
        self.model_time = None;
        self.status = "error".into();
        self.error = Some(message.to_owned());
    }
    pub(crate) fn new() -> Self {
        Self {
            fields: catalogue()
                .iter()
                .map(|v| {
                    (
                        v["id"].as_str().unwrap().to_owned(),
                        v["type"].as_str().unwrap().to_owned(),
                    )
                })
                .collect(),
            epoch: 1,
            session: None,
            retired: VecDeque::new(),
            aircraft: None,
            plane: None,
            model_time: None,
            sequence: None,
            received: None,
            status: "waiting".into(),
            values: BTreeMap::new(),
            malformed_frames: 0,
            error: None,
        }
    }
    pub(crate) fn feed(&mut self, bytes: &[u8], now_ms: u64) -> Result<bool, String> {
        let packet = match parse(bytes, &self.fields) {
            Ok(value) => value,
            Err(error) => {
                self.values.clear();
                self.status = "error".into();
                self.error = Some(error.clone());
                self.model_time = None;
                self.malformed_frames = self.malformed_frames.saturating_add(1);
                return Err(error);
            }
        };
        if self.retired.contains(&packet.session) {
            return Ok(false);
        }
        if self.session.as_ref() != Some(&packet.session) {
            if let Some(previous) = self.session.take() {
                self.retired.push_back(previous);
                if self.retired.len() > 16 {
                    self.retired.pop_front();
                }
            }
            self.session = Some(packet.session.clone());
            self.epoch = self.epoch.saturating_add(1);
            self.model_time = None;
            self.sequence = None;
            self.aircraft = None;
            self.plane = None;
        }
        if self.sequence.is_some_and(|previous| {
            let delta = packet.sequence.wrapping_sub(previous);
            delta == 0 || delta >= 1 << 31
        }) {
            return Ok(false);
        }
        let changed = self.aircraft != packet.aircraft || self.plane != packet.plane;
        let reversed = self
            .model_time
            .is_some_and(|previous| packet.model_time < previous);
        let advancing = !changed
            && !reversed
            && self
                .model_time
                .is_some_and(|previous| packet.model_time > previous);
        let frozen = !changed && self.model_time == Some(packet.model_time);
        if changed || reversed {
            self.epoch = self.epoch.saturating_add(1);
        }
        self.sequence = Some(packet.sequence);
        self.received = Some(now_ms);
        self.aircraft = packet.aircraft;
        self.plane = packet.plane;
        self.model_time = Some(packet.model_time);
        self.error = None;
        self.values.clear();
        self.status = if packet.stopped {
            "stopped"
        } else if !packet.allowed {
            "export-denied"
        } else if packet.paused || frozen {
            "paused"
        } else if self.aircraft.is_none()
            || self.plane.is_none()
            || !advancing
            || packet.values.is_empty()
        {
            "waiting"
        } else {
            self.values = packet.values;
            "live"
        }
        .into();
        Ok(true)
    }
    pub(crate) fn snapshot(&self, now_ms: u64) -> Snapshot {
        let age = self.received.map(|at| now_ms.saturating_sub(at));
        let expired = age.is_some_and(|age| age > FRESHNESS_MS);
        let fresh = !expired && self.status == "live";
        Snapshot {
            epoch: self.epoch,
            session: self.session.clone(),
            aircraft: self.aircraft.clone(),
            plane_id: self.plane,
            model_time: self.model_time,
            sequence: self.sequence,
            fresh,
            status: if expired && self.status != "stopped" {
                "stale".into()
            } else {
                self.status.clone()
            },
            age_ms: age,
            values: if fresh {
                self.values.clone()
            } else {
                BTreeMap::new()
            },
            malformed_frames: self.malformed_frames,
            error: self.error.clone(),
        }
    }
}
pub(crate) struct Source {
    socket: UdpSocket,
    session: Session,
    clock: Instant,
    draining: bool,
}
impl Source {
    pub(crate) fn open() -> Result<Self, String> {
        let socket =
            UdpSocket::bind(SocketAddrV4::new(Ipv4Addr::LOCALHOST, PORT)).map_err(|e| {
                format!("Cannot receive local DCS ownship telemetry on port {PORT}: {e}")
            })?;
        socket.set_nonblocking(true).map_err(|e| e.to_string())?;
        socket2::SockRef::from(&socket)
            .set_recv_buffer_size(256 * 1024)
            .map_err(|e| e.to_string())?;
        Ok(Self {
            socket,
            session: Session::new(),
            clock: Instant::now(),
            draining: false,
        })
    }
    pub(crate) fn poll(&mut self) -> Result<Snapshot, String> {
        let mut bytes = [0u8; MAX_PACKET + 1];
        let mut latest = None;
        for index in 0..=128 {
            match self.socket.recv_from(&mut bytes) {
                Ok((count, peer)) if peer.ip().is_loopback() => {
                    if index == 128 {
                        self.draining = true;
                        latest = None;
                        self.session.invalidate("DCS ownship export receive budget exceeded; queued frames are being discarded.");
                    } else if !self.draining {
                        latest = Some(bytes[..count].to_vec());
                    }
                }
                Ok(_) => {}
                Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                    self.draining = false;
                    break;
                }
                Err(error) => {
                    self.session
                        .invalidate("DCS ownship telemetry receive failed.");
                    return Err(format!("DCS ownship telemetry receive failed: {error}"));
                }
            }
        }
        if let Some(latest) = latest {
            let now = self.clock.elapsed().as_millis() as u64;
            if self
                .session
                .snapshot(now)
                .age_ms
                .is_some_and(|age| age > FRESHNESS_MS)
            {
                self.session
                    .invalidate("DCS ownship stream resumed; waiting for an advancing baseline.");
            }
            let _ = self.session.feed(&latest, now);
        }
        Ok(self.snapshot())
    }
    /// Clone the acquired frame with its current lease age, without touching
    /// the socket. Passive acquisition owns all UDP reads and their errors.
    pub(crate) fn snapshot(&self) -> Snapshot {
        self.session
            .snapshot(self.clock.elapsed().as_millis() as u64)
    }
}

