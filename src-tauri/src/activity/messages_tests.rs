use super::{operation, transition};

#[test]
fn profile_messages_are_plain_and_distinguish_requests_from_state() {
    assert_eq!(operation("profile_editor_save", Some("Race"), None, false), "Profile “Race” saved.");
    assert_eq!(operation("profile_apply", Some("Race"), None, false), "Activation requested for profile “Race”.");
    assert_eq!(operation("profile_apply", Some("Race"), None, true), "Could not request activation for profile “Race”.");
    assert_eq!(transition("profile_session", "degraded", "Race"), "Profile “Race” is degraded.");
    assert_eq!(transition("integration", "ready", "DCS World"), "DCS World integration is ready.");
}

