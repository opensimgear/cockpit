// Exercises the production Rust adapter, real C gateway and Cyphal module core.
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const workspace=fileURLToPath(new URL('../../',import.meta.url));
test('real native configuration survives save, layout apply, reboot and rejected flash writes',async()=>{
  const child=spawn(process.env.OSG_EMULATOR_SERVICE??resolve(workspace,'.research/cockpit-native-target/debug/osg-emulator-service'),[],{
    stdio:['pipe','pipe','inherit'],env:{...process.env,OSG_NATIVE_EMULATOR:process.env.OSG_NATIVE_EMULATOR??resolve(workspace,'.research/native-gateway/native-gateway')},
  });
  const pending=[];
  createInterface({input:child.stdout}).on('line',line=>{const task=pending.shift();if(task)task.resolve(JSON.parse(line));});
  child.once('error',error=>pending.splice(0).forEach(task=>task.reject(error)));
  const clientId='native-runtime-acceptance-client';
  const request=(command,extra={})=>new Promise((resolve,reject)=>{pending.push({resolve,reject});child.stdin.write(`${JSON.stringify({command,...extra,clientId})}\n`);});
  const ok=async(command,extra)=>{const result=await request(command,extra);assert.equal(result.ok,true,result.error);return result.state;};
  const admin=action=>ok('emulator',{action});
  try {
    let state=await ok('status');
    state=await ok('connect',{port:state.ports[0].path});
    const moduleId=state.modules[0].id;
    const original=await ok('config_read',{moduleId});
    const originalConfig=original.moduleConfigs[moduleId].config;
    state=await ok('claim',{moduleId});
    const config={name:'Complete controller é',expanderMask:1,buttons:[[0,0,1],[1,0,1],[24,1,0]],axes:[[0,48,100,3900,0,1,1000],[1,49,0,4095,32768,0,1200]],hats:[[2,3,4,5]],encoders:[[6,7]],selectors:[[8,9]]};
    state=await ok('config_apply_save',{moduleId,config});
    assert.deepEqual(state.moduleConfigs[moduleId].config,config);
    assert.equal(state.moduleConfigs[moduleId].pendingApply,false);
    assert.equal(state.moduleConfigs[moduleId].generation,state.moduleConfigs[moduleId].savedGeneration);
    assert.ok(state.claimedModules.includes(moduleId));
    await ok('release',{moduleId});
    state=await ok('register',{moduleId});
    assert.equal(state.needsReconnect,true);
    state=await ok('reconnect');
    assert.equal(state.needsReconnect,false);
    assert.equal(state.modules[0].profileMatch,true);
    assert.equal(state.modules[0].settings.label,config.name,'active name survives a same-gateway USB layout reconnect');
    assert.equal(state.modules[0].name,config.name,'device cards show the trusted active module name');
    const inspect=(await admin('inspect')).emulator;
    assert.ok(inspect);
    await admin('reboot module');
    state=await ok('status');
    assert.equal(state.moduleConfigs[moduleId],undefined,'a changed module boot invalidates cached runtime settings');
    state=await ok('config_read',{moduleId});
    assert.deepEqual(state.moduleConfigs[moduleId].config,config);
    await ok('claim',{moduleId});
    await admin('fault module 0');
    const rejected=await request('config_apply_save',{moduleId,config:{...config,name:'Failed persistent update'}});
    assert.equal(rejected.ok,false);
    state=await ok('config_read',{moduleId});
    assert.deepEqual(state.moduleConfigs[moduleId].config,config);
    await admin('fault module 4294967295');
    await ok('release',{moduleId});
    await ok('claim',{moduleId});
    const invalid=await request('config_apply_save',{moduleId,config:{...config,axes:[[0,48,4095,4095,0,0,0]]}});
    assert.equal(invalid.ok,false);
    await ok('release',{moduleId});
    await ok('claim',{moduleId});
    await admin('advance 40000');
    state=await ok('status');
    assert.deepEqual(state.claimedModules,[],'expired firmware leases require an explicit fresh setup session');
    await ok('claim',{moduleId});
    const volatile={...config,name:'Applied before lost save reply'};
    await ok('config_apply',{moduleId,config:volatile});
    await admin('drop_reply 1');
    const ambiguous=await request('config_save',{moduleId});
    assert.equal(ambiguous.ok,false,'persistent reply loss leaves the outcome for readback');
    assert.match(ambiguous.error,/reply was lost/);
    assert.deepEqual(ambiguous.state.claimedModules,[],'ambiguous commits end setup ownership');
    await admin('drop_reply 0');
    state=await ok('config_read',{moduleId});
    assert.deepEqual(state.moduleConfigs[moduleId].config,volatile);
    assert.equal(state.moduleConfigs[moduleId].generation,state.moduleConfigs[moduleId].savedGeneration);
    assert.deepEqual(state.claimedModules,[],'readback requires fresh setup ownership before another write');
    await admin('reboot module');
    state=await ok('status');
    state=await ok('config_read',{moduleId});
    assert.deepEqual(state.moduleConfigs[moduleId].config,volatile);
    const boot=state.modules[0].boot;
    const generation=state.modules[0].configurationGeneration;
    const externalName='External direct writer';
    await admin('direct_config claim 44');
    await admin('direct_config name 44 '+Buffer.from(externalName).toString('hex'));
    await admin('direct_config apply_save 44');
    state=await ok('status');
    assert.equal(state.modules[0].boot,boot,'an external writer can update configuration within the same module boot');
    assert.ok(state.modules[0].configurationGeneration>generation);
    assert.equal(state.needsApply,false,'name-only external changes preserve the gateway descriptor');
    assert.equal(state.moduleConfigs[moduleId],undefined,'a changed configuration generation invalidates active cache');
    state=await ok('config_read',{moduleId});
    assert.equal(state.moduleConfigs[moduleId].config.name,externalName);
    assert.equal(state.modules[0].name,externalName);
    await admin('direct_config release 44');
    assert.notDeepEqual(originalConfig,config);
  } finally { child.stdin.end(); await new Promise(resolve=>child.once('exit',resolve)); }
});
